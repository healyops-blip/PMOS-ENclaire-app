@dataclass(frozen=True, slots=True)
class PatientNoteRewriteRequest:
    original_text: str
    visit_context: str | None = None


class PatientNoteRewriteService:
    def __init__(self, provider: QwenChatProvider) -> None:
        self.provider = provider

    def rewrite(self, payload: PatientNoteRewriteRequest) -> str:
        user_prompt = (
            (f"就诊场景：{payload.visit_context}\n" if payload.visit_context else "")
            + "患者原文：\n"
            + payload.original_text.strip()
            + "\n\n请输出改写后的标准咨询话术，仅输出纯文本。"
        )
        request = ChatRequest(
            model=self.provider.model,
            messages=[
                {"role": "system", "content": REWRITE_SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ],
            temperature=0.2,
            top_p=0.9,
        )
        response = self.provider.chat(request)
        return response.content.strip()
